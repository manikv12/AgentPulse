type ProviderMarkProps = {
  provider?: AgentProvider;
  size?: 'sm' | 'md' | 'lg';
};

export function ProviderMark({ provider, size = 'sm' }: ProviderMarkProps) {
  const resolvedProvider = providerForThread(provider);
  if (resolvedProvider === 'claude-code') {
    return <ClaudeMark size={size} />;
  }
  if (resolvedProvider === 'copilot') {
    return <CopilotMark size={size} />;
  }

  return <CodexMark size={size} />;
}

